def square(x):
    return x * x

print(square(3))
print(square(5))

#square関数は、引数として渡された値の二乗を計算して返す関数です。例えば、square(3)は3の二乗である9を返し、square(5)は5の二乗である25を返します。
#このプログラムは、square関数を呼び出して値の二乗を計算しています。
#returnは、関数の実行結果を呼び出し元に返すためのキーワードです。

print(square(3))
print(square(5))

#つまり、自分で関数を定義して、引数を渡すことで、特定の計算や処理を行うことができます。